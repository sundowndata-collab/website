// Run: node _src/build-quote.mjs  (rebuilds api/quote.js from _src/quote.html and _src/quote-handler.js)
// The page is inlined into the function so the rates are never served as a public file.
import { readFileSync, writeFileSync } from 'fs';
const html = readFileSync(new URL('./quote.html', import.meta.url), 'utf8');
const login = readFileSync(new URL('./login.html', import.meta.url), 'utf8');
const handler = readFileSync(new URL('./quote-handler.js', import.meta.url), 'utf8')
  .replace("import PAGE from './_quote-page.js';", 'const PAGE = ' + JSON.stringify(html) + ';')
  .replace("import LOGIN from './_login-page.js';", 'const LOGIN = ' + JSON.stringify(login) + ';');
writeFileSync(new URL('../api/quote.js', import.meta.url), '// Generated by _src/build-quote.mjs. Edit _src/quote.html, then rebuild.\n' + handler);
